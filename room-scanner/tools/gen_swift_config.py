#!/usr/bin/env python3
"""config.yaml -> ios/RoomScanner/Capture/GeneratedConfig.swift  (run after editing the `capture:` section)."""
from pathlib import Path
import yaml
root = Path(__file__).resolve().parent.parent
c = yaml.safe_load(open(root / "config.yaml"))["capture"]
out = root / "ios/RoomScanner/Capture/GeneratedConfig.swift"
out.write_text(f"""// GENERATED by tools/gen_swift_config.py from config.yaml — do not edit by hand.
enum GeneratedConfig {{
    static let keyframeTranslationM: Float = {float(c['keyframe_translation_m'])}
    static let keyframeRotationDeg: Float = {float(c['keyframe_rotation_deg'])}
    static let blurLaplacianMin: Double = {float(c['blur_laplacian_min'])}
}}
""")
print("wrote", out)
